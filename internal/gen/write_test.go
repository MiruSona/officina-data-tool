package gen

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestWriteAndStale(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "Generated")
	files, err := Generate(load(t))
	if err != nil {
		t.Fatal(err)
	}

	stale, err := Write(dir, files)
	if err != nil {
		t.Fatalf("쓰기 실패 : %v", err)
	}
	if len(stale) != 0 {
		t.Errorf("빈 폴더인데 남은 파일이 있다 : %v", stale)
	}
	for name, want := range files {
		got, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatalf("%s 를 못 읽었다 : %v", name, err)
		}
		if string(got) != want {
			t.Errorf("%s 내용이 다르다", name)
		}
	}
	// 임시 파일이 남으면 안 된다.
	entries, _ := os.ReadDir(dir)
	for _, e := range entries {
		if strings.HasPrefix(e.Name(), ".datatool-gen-") {
			t.Errorf("임시 파일이 남았다 : %s", e.Name())
		}
	}

	// 옛 생성 파일 하나와 사람이 둔 파일 하나를 넣고 다시 쓴다.
	old := filepath.Join(dir, "GhostRow.cs")
	if err := os.WriteFile(old, []byte("// <auto-generated>\n// 옛 표\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	mine := filepath.Join(dir, "MyHand.cs")
	if err := os.WriteFile(mine, []byte("// 사람이 쓴 것\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	stale, err = Write(dir, files)
	if err != nil {
		t.Fatal(err)
	}
	if len(stale) != 1 || stale[0] != "GhostRow.cs" {
		t.Errorf("남은 생성 파일을 못 집었다 : %v", stale)
	}
	// 알리기만 하고 지우지 않는다 (설계 8장).
	if _, err := os.Stat(old); err != nil {
		t.Error("남은 생성 파일을 지웠다 — 알리기만 해야 한다")
	}
	if _, err := os.Stat(mine); err != nil {
		t.Error("사람이 둔 파일이 사라졌다")
	}
}

func TestWriteRejectsBadNames(t *testing.T) {
	dir := t.TempDir()
	for _, name := range []string{"../out.cs", "sub/out.cs", `sub\out.cs`, "out.txt", ""} {
		if _, err := Write(dir, map[string]string{name: "// x"}); err == nil {
			t.Errorf("%q 를 받았다", name)
		}
	}
}

// 덮어쓰기는 한 걸음이어야 한다 — 먼저 지우고 이름을 바꾸면 이름 바꾸기가 실패할 때 옛 파일까지 없어진다 (리뷰 D10).
func TestWriteOverwritesInOneStep(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "ItemRow.cs")
	if err := os.WriteFile(path, []byte("// 옛 내용\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := writeOne(path, "// 새 내용\n"); err != nil {
		t.Fatalf("덮어쓰기 실패 : %v", err)
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("덮어쓴 파일을 못 읽었다 : %v", err)
	}
	if string(got) != "// 새 내용\n" {
		t.Errorf("내용이 다르다 : %q", string(got))
	}

	// 쓰다 실패해도 옛 파일은 남아 있어야 한다 (폴더를 못 쓰게 만들어 흉내낸다).
	sub := filepath.Join(dir, "없는폴더", "ItemRow.cs")
	if err := writeOne(sub, "// 어디에도 못 쓴다\n"); err == nil {
		t.Fatal("없는 폴더에 썼는데 통과했다")
	}
	if _, err := os.Stat(path); err != nil {
		t.Errorf("실패한 쓰기가 다른 파일을 건드렸다 : %v", err)
	}
}
