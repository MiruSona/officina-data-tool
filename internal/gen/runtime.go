package gen

import (
	"fmt"
	"strings"

	unity "github.com/mirusona/officina-data-tool/Unity"
)

// AsmdefExt 는 Unity 어셈블리 정의 파일의 확장자다. 생성 폴더에 나가는 유일한 비 .cs 파일이다.
const AsmdefExt = ".asmdef"

// runtimeFiles 는 `Unity/` 의 손으로 쓴 셋을 스키마의 namespace 로 갈아 끼워 준다.
//
// **왜 gen 이 같이 내나** : 손으로 복사하고 손으로 치환하면 「`Officina.` 잔여 0」(설계 8장)을
// 아무도 안 센다. 여기서 같이 내면 ReplaceNamespace 가 매번 세고, 하나라도 남으면 오류다.
//
// asmdef 는 파일 이름이 곧 어셈블리 이름이라 `<namespace>.asmdef` 로 나간다.
func runtimeFiles(namespace string, hash string) (map[string]string, error) {
	out := map[string]string{}

	for _, name := range []string{unity.LoaderFile, unity.ExceptionFile} {
		src, err := readTemplate(name)
		if err != nil {
			return nil, err
		}
		replaced, err := ReplaceNamespace(src, namespace)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		// 머리 경고는 치환 뒤에 얹는다. 경고 줄에는 바꿀 것이 없다.
		out[name] = header(hash) + replaced
	}

	src, err := readTemplate(unity.AsmdefFile)
	if err != nil {
		return nil, err
	}
	replaced, err := ReplaceNamespace(src, namespace)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", unity.AsmdefFile, err)
	}
	out[namespace+AsmdefExt] = markAsmdef(replaced, hash)
	return out, nil
}

func readTemplate(name string) (string, error) {
	data, err := unity.FS.ReadFile(name)
	if err != nil {
		return "", fmt.Errorf("exe 안의 %s 를 못 읽었다 : %w", name, err)
	}
	// 생성 폴더에 나가는 파일은 줄바꿈을 LF 로 통일한다 — 생성 .cs 와 섞이지 않게.
	return strings.ReplaceAll(string(data), "\r\n", "\n"), nil
}

// markAsmdef 는 asmdef 에 생성 표시를 얹는다.
//
// JSON 이라 `//` 주석을 못 쓴다. 그래서 칸 하나를 맨 앞에 끼워 넣는다 —
// Unity 의 asmdef 읽기는 모르는 칸을 조용히 넘기므로 안전하고,
// `<auto-generated>` 글자가 들어가 있어 옛 파일 찾기(findStale)가 .cs 와 같은 잣대로 센다.
func markAsmdef(src string, hash string) string {
	const key = "    \"_generated\": "
	note := "<auto-generated> datatool gen 이 만든 파일이다. 손대지 마라 — 다음 gen 에서 통째로 덮인다. schemaHash : " + hash
	line := key + quote(note) + ",\n"

	at := strings.Index(src, "{\n")
	if at < 0 {
		return src // 꼴이 다르면 손대지 않는다. 치환은 이미 끝났다.
	}
	return src[:at+2] + line + src[at+2:]
}
