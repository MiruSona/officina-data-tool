package gen

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Write 는 Generate 가 만든 파일 묶음을 생성 폴더에 쓴다.
//
// 한 장씩 임시 파일에 쓰고 이름을 바꾼다 — 중간에 멈춰도 반쯤 쓰인 `.cs` 가 안 남는다.
// 돌려주는 stale 은 **이번에 안 나왔는데 폴더에 남아 있는 생성 파일**이다.
// 지우지는 않는다 (설계 8장) — 표를 없앴을 때 남는 파일은 사람이 보고 지운다.
func Write(dir string, files map[string]string) (stale []string, err error) {
	if strings.TrimSpace(dir) == "" {
		return nil, fmt.Errorf("생성 폴더 경로가 비었다")
	}
	for name := range files {
		if err := checkName(name); err != nil {
			return nil, err
		}
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, fmt.Errorf("생성 폴더를 만들지 못했다 : %w", err)
	}

	for _, name := range sortedKeys(files) {
		if err := writeOne(filepath.Join(dir, name), files[name]); err != nil {
			return nil, err
		}
	}

	stale, err = findStale(dir, files)
	if err != nil {
		return nil, err
	}
	return stale, nil
}

// checkName 은 파일 이름이 생성 폴더 안에만 머무는지 본다.
// 하위 폴더도 `..` 도 받지 않는다 — 쓰는 자리를 한 겹으로 묶어 둔다.
func checkName(name string) error {
	if name == "" || name == "." || name == ".." {
		return fmt.Errorf("생성 파일 이름이 이상하다 : %q", name)
	}
	if strings.ContainsAny(name, `/\`) || filepath.Base(name) != name {
		return fmt.Errorf("생성 파일 이름에 경로가 들어 있다 : %q", name)
	}
	if !generatedFile(name) {
		return fmt.Errorf("생성 파일은 .cs 나 %s 여야 한다 : %q", AsmdefExt, name)
	}
	return nil
}

// generatedFile 은 생성 폴더가 다루는 확장자인지 본다.
// asmdef 하나만 .cs 가 아니다 — 그것도 gen 이 내므로 옛 파일 찾기도 같이 본다.
func generatedFile(name string) bool {
	return strings.HasSuffix(name, ".cs") || strings.HasSuffix(name, AsmdefExt)
}

// writeOne 은 파일 한 장을 tmp → 이름 바꾸기로 쓴다.
func writeOne(path string, content string) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, ".datatool-gen-*")
	if err != nil {
		return fmt.Errorf("임시 파일을 만들지 못했다 (%s) : %w", dir, err)
	}
	tmpPath := tmp.Name()
	defer os.Remove(tmpPath) // 이름 바꾸기가 끝났으면 없어서 실패하고, 그건 괜찮다.

	if _, err := tmp.WriteString(content); err != nil {
		tmp.Close()
		return fmt.Errorf("생성 파일을 쓰지 못했다 (%s) : %w", path, err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("생성 파일을 닫지 못했다 (%s) : %w", path, err)
	}
	// 윈도에서는 이름 바꾸기가 기존 파일을 덮지 못할 때가 있어 먼저 치운다.
	_ = os.Remove(path)
	if err := os.Rename(tmpPath, path); err != nil {
		return fmt.Errorf("생성 파일 이름을 바꾸지 못했다 (%s) : %w", path, err)
	}
	return nil
}

// findStale 은 폴더에 남아 있는 옛 생성 파일을 찾는다.
// 생성 파일인지는 머리의 <auto-generated> 표시로 가른다 — 사람이 둔 파일은 건드리지도, 알리지도 않는다.
func findStale(dir string, files map[string]string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("생성 폴더를 읽지 못했다 (%s) : %w", dir, err)
	}

	var stale []string
	for _, e := range entries {
		if e.IsDir() || !generatedFile(e.Name()) {
			continue
		}
		if _, ok := files[e.Name()]; ok {
			continue
		}
		head, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, fmt.Errorf("생성 폴더의 파일을 읽지 못했다 (%s) : %w", e.Name(), err)
		}
		if strings.Contains(string(head), "<auto-generated>") {
			stale = append(stale, e.Name())
		}
	}
	sort.Strings(stale)
	return stale, nil
}

func sortedKeys(files map[string]string) []string {
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
